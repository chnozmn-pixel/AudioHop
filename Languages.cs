        private static readonly Dictionary<string, Dictionary<string, string>> table =
            new Dictionary<string, Dictionary<string, string>>(StringComparer.OrdinalIgnoreCase);
        private static readonly Dictionary<string, string> names =
            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        private static readonly List<string> rightToLeft = new List<string> { "ar", "he", "fa", "ur" };

        /// <summary>Active language code, e.g. "tr".</summary>
        public static string Code = "en";
        public static bool Rtl;

        private static Dictionary<string, string> active;
        private static Dictionary<string, string> english;
        private static bool built;

        /// <summary>Codes and native names, ready for a drop-down.</summary>
        public static List<KeyValuePair<string, string>> Available
        {
            get
            {
                Build();
                var list = new List<KeyValuePair<string, string>>();
                foreach (var pair in names) list.Add(pair);
                list.Sort(delegate(KeyValuePair<string, string> a, KeyValuePair<string, string> b)
                {
                    return string.Compare(a.Value, b.Value, StringComparison.CurrentCulture);
                });
                return list;
            }
        }

        /// <summary>preferred is "auto" or a language code.</summary>
        public static void Init(string preferred)
        {
            Build();

            string code = preferred;
            if (string.IsNullOrEmpty(code) || code == "auto")
                code = System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;

            if (!table.TryGetValue(code, out active))
            {
                code = "en";
                active = english;
            }
            Code = code;
            Rtl = rightToLeft.Contains(code.ToLowerInvariant());
        }

        public static string T(string key, params object[] args)
        {
            if (active == null) Init("auto");

            string text;
            if (!active.TryGetValue(key, out text) && !english.TryGetValue(key, out text))
                text = key;

            if (args == null || args.Length == 0) return text;
            try { return string.Format(text, args); }
            catch { return text; }
        }

        private static void Add(string code, string nativeName, string[] pairs)
        {
            var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i + 1 < pairs.Length; i += 2) map[pairs[i]] = pairs[i + 1];
            table[code] = map;
            names[code] = nativeName;
        }

        /// <summary>Reads %APPDATA%\AudioHop\lang\*.lang over the built-in text.</summary>
        private static void LoadExternal()
        {
            try
            {
                string dir = System.IO.Path.Combine(Config.Folder, "lang");
                if (!System.IO.Directory.Exists(dir)) return;

                foreach (var file in System.IO.Directory.GetFiles(dir, "*.lang"))
                {
                    string code = System.IO.Path.GetFileNameWithoutExtension(file);
                    Dictionary<string, string> map;
                    if (!table.TryGetValue(code, out map))
                    {
                        map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                        table[code] = map;
                        names[code] = code;
                    }

                    foreach (var line in System.IO.File.ReadAllLines(file))
                    {
                        if (line.StartsWith("#")) continue;
                        int eq = line.IndexOf('=');
                        if (eq <= 0) continue;

                        string key = line.Substring(0, eq).Trim().TrimStart('\uFEFF');
                        string value = line.Substring(eq + 1).Replace("\\n", "\n");
                        if (key == "language.name") names[code] = value.Trim();
                        else map[key] = value;
                    }
                }
            }
            catch { /* a bad language file must never stop the app */ }
        }

