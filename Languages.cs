// AudioHop - translations.
//
// Adding a language without touching this file: drop a UTF-8 text file named
// <code>.lang (e.g. "sv.lang") into %APPDATA%\AudioHop\lang\ with lines like
//     language.name=Svenska
//     menu.exit=Avsluta
// Any key you leave out falls back to English. Files there also override the
// built-in text, so a wording you dislike can be fixed without rebuilding.
